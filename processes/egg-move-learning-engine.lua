    end
    
    -- Extract moves from parent 2
    if parent2Data and parent2Data.moves then
        for _, moveId in ipairs(parent2Data.moves) do
            table.insert(parentMoves.parent2.moveSet, moveId)
        end
    end
    if parent2Data and parent2Data.eggMoves then
        for _, moveId in ipairs(parent2Data.eggMoves) do
            table.insert(parentMoves.parent2.eggMoves, moveId)
        end
    end
    
    return parentMoves
end

local function calculateMovePriority(moveId, parentMoves, speciesEggMoves)
    -- Check if move is known by both parents
    local inParent1 = false
    local inParent2 = false
    
    for _, m in ipairs(parentMoves.parent1.moveSet) do
        if m == moveId then
            inParent1 = true
            break
        end
    end
    if not inParent1 then
        for _, m in ipairs(parentMoves.parent1.eggMoves) do
            if m == moveId then
                inParent1 = true
                break
            end
        end
    end
    
    for _, m in ipairs(parentMoves.parent2.moveSet) do
        if m == moveId then
            inParent2 = true
            break
        end
    end
    if not inParent2 then
        for _, m in ipairs(parentMoves.parent2.eggMoves) do
            if m == moveId then
                inParent2 = true
                break
            end
        end
    end
    
    -- Both parents know the move - highest priority
    if inParent1 and inParent2 then
        return MOVE_PRIORITY.parent_egg
    end
    
    -- One parent knows the move
    if inParent1 or inParent2 then
        return MOVE_PRIORITY.parent_one
    end
    
    -- Check if it's in species egg move pool
    for _, m in ipairs(speciesEggMoves) do
        if m == moveId then
            return MOVE_PRIORITY.egg_pool
        end
    end
    
    -- Default to level-up priority
    return MOVE_PRIORITY.level_up
end

-- ============================================================================
-- MOVE INHERITANCE LOGIC
-- ============================================================================

local function determineInheritedMoves(parentMoves, speciesId)
    local speciesEggMoves = getSpeciesEggMoves(speciesId)
    local inheritedMoves = {}
    local movePriorities = {}
    
    -- Collect all potential moves
    local allMoves = {}
    local moveSet = {}
    
    -- Add species egg moves
    for _, moveId in ipairs(speciesEggMoves) do
        if not moveSet[moveId] then
            moveSet[moveId] = true
            table.insert(allMoves, moveId)
        end
    end
    
    -- Add parent 1 moves
    for _, moveId in ipairs(parentMoves.parent1.moveSet) do
        if not moveSet[moveId] then
            moveSet[moveId] = true
            table.insert(allMoves, moveId)
        end
    end
    for _, moveId in ipairs(parentMoves.parent1.eggMoves) do
        if not moveSet[moveId] then
            moveSet[moveId] = true
            table.insert(allMoves, moveId)
        end
    end
    
    -- Add parent 2 moves
    for _, moveId in ipairs(parentMoves.parent2.moveSet) do
        if not moveSet[moveId] then
            moveSet[moveId] = true
            table.insert(allMoves, moveId)
        end
    end
    for _, moveId in ipairs(parentMoves.parent2.eggMoves) do
        if not moveSet[moveId] then
            moveSet[moveId] = true
            table.insert(allMoves, moveId)
        end
    end
    
    -- Calculate priority for each move
    for _, moveId in ipairs(allMoves) do
        local priority = calculateMovePriority(moveId, parentMoves, speciesEggMoves)
        table.insert(movePriorities, {moveId = moveId, priority = priority})
    end
    
    -- Sort by priority (lower number = higher priority)
    table.sort(movePriorities, function(a, b)
        return a.priority < b.priority
    end)
    
    -- Select up to MAX_MOVE_SLOTS moves
    for i = 1, math.min(MAX_MOVE_SLOTS, #movePriorities) do
        table.insert(inheritedMoves, movePriorities[i].moveId)
    end
    
    return inheritedMoves
end

-- ============================================================================
-- CHAIN BREEDING LOGIC
-- ============================================================================

local function applyChainBreeding(moveId, parentMoves, chainDepth)
    -- Implement chain breeding mechanics
    -- Allows moves to be passed through breeding chains
    if not ENABLE_CHAIN_BREEDING then
        return false
    end
    
    chainDepth = chainDepth or 1
    if chainDepth > MAX_CHAIN_LENGTH then
        return false
    end
    
    -- Check if move can be chain bred
    -- A move can be chain bred if:
    -- 1. One parent knows it as an egg move
    -- 2. The move is compatible with the offspring species
    -- 3. The chain depth hasn't exceeded maximum
    
    local parent1HasAsEgg = false
    local parent2HasAsEgg = false
    
    if parentMoves and parentMoves.parent1 and parentMoves.parent1.eggMoves then
        for _, eggMove in ipairs(parentMoves.parent1.eggMoves) do
            if eggMove == moveId then
                parent1HasAsEgg = true
                break
            end
        end
    end
    
    if parentMoves and parentMoves.parent2 and parentMoves.parent2.eggMoves then
        for _, eggMove in ipairs(parentMoves.parent2.eggMoves) do
            if eggMove == moveId then
                parent2HasAsEgg = true
                break
            end
        end
    end
    
    -- Move can be chain bred if either parent has it as an egg move
    return parent1HasAsEgg or parent2HasAsEgg
end

-- ============================================================================
-- MOVE SLOT MANAGEMENT
-- ============================================================================

local function manageMoveSlots(currentMoves, newMove, slotToReplace)
    local result = {}
    
    -- Copy current moves
    for i = 1, MAX_MOVE_SLOTS do
        result[i] = currentMoves[i]
    end
    
    -- Check if move already exists
    for i = 1, MAX_MOVE_SLOTS do
        if result[i] == newMove then
            return result, "Move already known"
        end
    end
    
    -- If slot specified, replace it
    if slotToReplace then
        local slotNum = tonumber(slotToReplace)
        if slotNum >= 1 and slotNum <= MAX_MOVE_SLOTS then
            result[slotNum] = newMove
            return result, nil
        end
    end
    
    -- Find empty slot
    for i = 1, MAX_MOVE_SLOTS do
        if not result[i] or result[i] == 0 then
            result[i] = newMove
            return result, nil
        end
    end
    
    -- All slots full, need to specify replacement
    return currentMoves, "All move slots full - specify slot to replace"
end

