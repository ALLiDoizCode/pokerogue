local function getSpeciesEggMoves(speciesId)
    local id = tonumber(speciesId)
    if not id then
        return {}
    end
    
    local moves = EggMoveDatabase[id]
    if not moves then
        return {}
    end
    
    -- Return a copy to prevent modification
    local result = {}
    for i, moveId in ipairs(moves) do
        result[i] = moveId
    end
    return result
end

